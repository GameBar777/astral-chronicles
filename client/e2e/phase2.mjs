// E2E: auth -> character creation -> 3/4 world (movement, footprint collision, Y-sort occlusion, camera, JP font)
import { chromium } from 'playwright';
const URL = process.env.E2E_URL ?? 'http://127.0.0.1:5173/';
const SHOT = new globalThis.URL('../../docs/screenshots/', import.meta.url).pathname;
const results = []; const ok = (name, cond, info = '') => { results.push({ name, pass: !!cond }); console.log(`${cond ? 'PASS' : 'FAIL'} ${name} ${info}`); };
const b = await chromium.launch({ args: ['--use-gl=swiftshader', '--enable-unsafe-swiftshader'] });
const p = await b.newPage({ viewport: { width: 1280, height: 800 } });
const errors = []; p.on('pageerror', (e) => errors.push(String(e))); p.on('console', (m) => m.type() === 'error' && !/status of 4(00|09)/.test(m.text()) && errors.push(m.text()));
await p.goto(URL); await p.waitForSelector('#email');
ok('font DotGothic16 loaded', await p.evaluate(() => document.fonts.check('16px "DotGothic16"', 'ギルド')));
await p.screenshot({ path: SHOT + 'phase2-login.png' });
const email = `e2e_${Date.now()}@example.com`;
await p.fill('#email', email); await p.fill('#pw', 'short'); await p.click('#reg');
await p.waitForFunction(() => document.querySelector('#err')?.textContent);
ok('short password rejected (JP msg)', /パスワード/.test(await p.textContent('#err')));
await p.fill('#pw', 'correct-horse-9'); await p.click('#reg');
await p.waitForSelector('#new'); ok('register+login -> character select', true);
await p.click('#new'); await p.waitForSelector('#name');
await p.fill('#name', '管理者テスト'); await p.click('#create');
await p.waitForFunction(() => document.querySelector('#err')?.textContent);
ok('banned name rejected', /使用できない語句/.test(await p.textContent('#err')));
const name = 'テスト' + String.fromCharCode(0x30a2 + (Date.now() % 40));
await p.fill('#name', name); await p.check('input[value=mage]'); await p.selectOption('#hc', '3');
await p.screenshot({ path: SHOT + 'phase2-create.png' });
await p.click('#create');
await p.waitForFunction(() => window.__astral?.scene.isActive('World'), null, { timeout: 15000 });
await p.waitForTimeout(800);
const W = () => p.evaluate(() => { const s = window.__astral.scene.getScene('World'); const c = s.cameras.main;
  return { x: s.pos.x, y: s.pos.y, depth: s.player.depth, cls: s.character.class, lv: s.character.level, camX: c.midPoint.x, camY: c.midPoint.y, bounds: { w: c.getBounds().width, h: c.getBounds().height } }; });
let s = await W();
ok('entered world at server spawn', Math.abs(s.x - 720) < 2 && Math.abs(s.y - 698) < 2, JSON.stringify(s));
ok('character class/level from server', s.cls === 'mage' && s.lv === 1);
ok('HUD shows Lv1', await p.evaluate(() => window.__astral.scene.getScene('Hud').children.list.some((o) => o.text?.includes('Lv.1'))));
await p.screenshot({ path: SHOT + 'phase2-world-spawn.png' });
const hold = async (k, ms) => { await p.keyboard.down(k); await p.waitForTimeout(ms); await p.keyboard.up(k); await p.waitForTimeout(150); };
await hold('ArrowRight', 500); const s2 = await W(); ok('moves right', s2.x > s.x + 30, `${s.x}->${s2.x}`);
ok('camera follows', Math.abs(s2.camX - s2.x) < 40 && Math.abs(s2.camY - s2.y) < 40, `${s2.camX},${s2.camY}`);
ok('camera bounds = map size', s2.bounds.w === 44 * 32 && s2.bounds.h === 34 * 32);
// Y-sort: put player just north of guild house footprint (tiles x9-13, y6-8, bottom y=288)
const tp = (x, y) => p.evaluate(([x, y]) => { window.__astral.scene.getScene('World').pos = { x, y }; }, [x, y]);
await tp(368, 186); await p.waitForTimeout(200);
const house = await p.evaluate(() => window.__astral.scene.getScene('World').props.find((o) => o.x === 368 && o.getData('kind') === 'house').depth);
s = await W(); ok('behind house: player depth < house depth (occluded)', s.depth < house, `${s.depth} < ${house}`);
await p.screenshot({ path: SHOT + 'phase2-behind-house.png' });
await hold('ArrowDown', 900); s = await W(); ok('house footprint blocks southward move', s.y <= 192.01, `y=${s.y}`);
await tp(368, 300); await p.waitForTimeout(200); s = await W(); ok('in front of house: depth > house depth', s.depth > house);
await hold('ArrowUp', 900); s = await W(); ok('house footprint blocks northward move', s.y >= 288 + 12 - 0.01, `y=${s.y}`);
await p.screenshot({ path: SHOT + 'phase2-front-house.png' });
// fountain footprint (20..23,15..17)
await tp(704, 610); await hold('ArrowUp', 900); s = await W(); ok('fountain blocks', s.y >= 576 + 12 - 0.01, `y=${s.y}`);
// map edge
await tp(720, 698); await hold('ArrowLeft', 7000); s = await W(); ok('westward walk stops at an obstacle (never leaves map)', s.x > 32, `x=${s.x}`);
await tp(720, 640); await p.waitForTimeout(400); await p.screenshot({ path: SHOT + 'phase2-plaza.png' });
// logout
await p.click('#logout'); await p.waitForSelector('#email');
ok('logout returns to login', /ログアウト/.test(await p.textContent('#err')));
ok('token cleared', await p.evaluate(() => !sessionStorage.getItem('astral.token')));
ok('no page errors', errors.length === 0, errors.join(' | '));
await b.close();
const f = results.filter((r) => !r.pass).length; console.log(`\n${results.length - f}/${results.length} passed`); process.exit(f ? 1 : 0);
