// Generates assets/maps/asteria.json (TEMP placeholder layout; replace with Tiled-authored map later)
import { writeFileSync } from 'node:fs';
const W = 40, H = 30; // tiles (32px)
const T = { GRASS: 1, PATH: 2, WATER: 3, WALL: 4, TREE: 5, PLAZA: 6, ROOF: 7 };
const ground = Array(W * H).fill(T.GRASS), col = Array(W * H).fill(0);
const set = (x, y, t, solid = false) => { ground[y * W + x] = t; col[y * W + x] = solid ? 1 : 0; };
for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) if (x === 0 || y === 0 || x === W - 1 || y === H - 1) set(x, y, T.TREE, true);
for (let x = 1; x < W - 1; x++) { set(x, 15, T.PATH); set(x, 14, T.PATH); }
for (let y = 1; y < H - 1; y++) { set(20, y, T.PATH); set(19, y, T.PATH); }
for (let y = 11; y <= 18; y++) for (let x = 16; x <= 23; x++) set(x, y, T.PLAZA);
for (let y = 13; y <= 16; y++) for (let x = 19; x <= 20; x++) set(x, y, T.WATER, true); // fountain
const house = (hx, hy, w, h) => { for (let y = hy; y < hy + h; y++) for (let x = hx; x < hx + w; x++) set(x, y, y < hy + 2 ? T.ROOF : T.WALL, true); set(hx + (w >> 1), hy + h - 1, T.PATH); /* door tile still solid? no: door walkable */ };
house(5, 4, 6, 5); house(28, 4, 7, 5); house(5, 20, 6, 5); house(28, 20, 6, 5);
for (let y = 22; y <= 27; y++) for (let x = 13; x <= 16; x++) set(x, y, T.WATER, true); // pond
[[3,12],[12,9],[25,10],[35,13],[12,18],[25,25],[36,17]].forEach(([x, y]) => set(x, y, T.TREE, true));
const map = { id: 'asteria', name: '始まりの街 アステリア', width: W, height: H, tilewidth: 32, tileheight: 32,
  recommendedLevel: [1, 5], spawn: { x: 18 * 32 + 16, y: 20 * 32 + 24 },
  layers: [{ name: 'ground', data: ground }, { name: 'collision', data: col }],
  objects: [
    { id: 'npc_guild_receptionist', type: 'npc', x: 8 * 32 + 16, y: 10 * 32, props: { name: 'ギルド受付 ミーナ' } },
    { id: 'portal_to_meadow', type: 'portal', x: 38 * 32, y: 15 * 32, props: { to: 'green_meadow', placeholder: true } }],
  _note: 'TEMP placeholder map generated by scripts/gen-asteria-map.mjs' };
writeFileSync(new URL('../assets/maps/asteria.json', import.meta.url), JSON.stringify(map));
console.log('wrote asteria.json', W, 'x', H);
